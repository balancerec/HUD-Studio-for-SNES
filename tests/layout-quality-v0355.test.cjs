const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const QA=require('../scripts/layout-quality.js');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const refs=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/manual-layout-profiles-v0353.json'),'utf8'));
const ids=Object.keys(refs.profiles['1920x1080'].items);
const sprites=ids.map(id=>({id,label:'sprite '+id}));
assert.equal(Object.keys(QA.MODES).length,6);
for(const [key,profile] of Object.entries(refs.profiles))assert.equal(QA.validateProfile(profile,key,ids).ok,true,key);
const report=QA.auditProfiles(refs.profiles,sprites);
assert.equal(report.summary.valid,6);
const damaged=JSON.parse(JSON.stringify(refs.profiles['1920x1080']));
damaged.items[ids[0]].w=0;
assert.equal(QA.validateProfile(damaged,'1920x1080',ids).ok,false);
damaged.items[ids[0]].w=NaN;
assert.equal(QA.validateProfile(damaged,'1920x1080',ids).ok,false);
const mismatched={...refs.profiles['1920x1080'],width:700};
assert.equal(QA.validateProfile(mismatched,'1920x1080',ids).ok,false);
const tiny={width:1920,height:1080,items:{[ids[0]]:{x:0,y:0,w:50,h:50}}};
assert.equal(QA.validateProfile(tiny,'1920x1080',ids).ok,false);
const offscreen=JSON.parse(JSON.stringify(refs.profiles['1920x1080']));
offscreen.items[ids[0]]={x:-500,y:20,w:50,h:50};
const modified={...refs.profiles,'1920x1080':offscreen};
assert.ok(QA.auditProfiles(modified,sprites).modes['1920x1080'].clipped.some(x=>x.id===ids[0]));
const smokeSprites=sprites.map(s=>({...s,label:s.id===ids[0]?'Fumaça':s.label}));
assert.ok(!QA.auditProfiles(modified,smokeSprites).modes['1920x1080'].clipped.some(x=>x.id===ids[0]));
assert.match(html,/id="layoutAuditBtn"/);
assert.match(html,/function auditCurrentLayout\(/);
assert.match(html,/HUDLayoutQuality\.validateProfile\(saved/);
assert.match(html,/scripts\/layout-quality\.js/);
assert.match(html,/layoutAuditExport/);
console.log('Layout Quality v0.3.5.5: six presets, validation, clipping, smoke exemptions, UI and fallback OK');
